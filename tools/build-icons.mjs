// Build /icon-svgs.js from tools/icon-map.mjs using Iconify JSON sets installed in ICONSRC (default /tmp/iconsrc).
// Usage: npm i --prefix /tmp/iconsrc @iconify-json/{tabler,ph,mdi,material-symbols,game-icons,icon-park-outline,lucide}; node tools/build-icons.mjs
import fs from 'fs';import path from 'path';import {fileURLToPath} from 'url';
import {SETS,ICONS,CUSTOM} from './icon-map.mjs';
const SRC=process.env.ICONSRC||'/tmp/iconsrc',ROOT=path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const cache={};const load=s=>cache[s]??=JSON.parse(fs.readFileSync(`${SRC}/node_modules/@iconify-json/${s}/icons.json`,'utf8'));
function get(set,name){const j=load(set);let n=name,seen=0;while(j.aliases?.[n]&&seen++<5)n=j.aliases[n].parent;const i=j.icons[n];if(!i)return null;
 const w=i.width||j.width||16,h=i.height||j.height||16;let b=i.body;
 if(w!==24||h!==24){const s=24/Math.max(w,h),tx=(24-w*s)/2,ty=(24-h*s)/2;b=`<g transform="translate(${+tx.toFixed(2)} ${+ty.toFixed(2)}) scale(${+s.toFixed(5)})">${b}</g>`}
 return b}
const opt=s=>s.replace(/\s+/g,' ').replace(/> </g,'><').replace(/(\d+\.\d{2})\d+/g,'$1');
import {KEYWORDS,CATEGORIES} from '../icons.js';
const USED=new Set([...KEYWORDS.map(k=>k.icon),...CATEGORIES.map(c=>c.icon),'cart']);// only icons actually referenced
const out={},report=[];
for(const[key,cands]of Object.entries(ICONS)){if(!USED.has(key))continue;let got=null,from='';
 for(const c of cands.split(/\s+/)){
  if(c.startsWith('custom:')){const b=CUSTOM[c.slice(7)];if(b){got=b;from=c;break}continue}
  if(c.includes(':')){const[s,n]=c.split(':');if(SETS.includes(s)){got=get(s,n);if(got){from=c;break}}continue}
  for(const s of SETS){got=get(s,c);if(got){from=s+':'+c;break}}if(got)break}
 if(got){out[key]=opt(got);report.push(`${key}=${from}`)}else report.push(`MISSING ${key} (${cands})`)}
const js=`// GENERATED by tools/build-icons.mjs - do not edit. Iconify sets (tabler, lucide, ph, mdi, game-icons, icon-park, material-symbols); 24x24, currentColor.\nexport const ICON_SVGS=${JSON.stringify(out)};\n`;
fs.writeFileSync(path.join(ROOT,'icon-svgs.js'),js);
console.log(report.filter(r=>r.startsWith('MISSING')).join('\n'));console.log(Object.keys(out).length,'icons',(js.length/1024).toFixed(0),'KB');
if(process.env.VERBOSE)console.log(report.join('\n'));
